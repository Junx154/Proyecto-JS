let promedio = parseFloat(prompt("ingrese su promedio:"));

if (promedio >= 18 && promedio <=20) {
    console.log("rendimeinto excelente");
} else if (promedio >=14) {
    console.log ("buen rendimiento.");
} else if (promedio >= 11) {
    console.log ("en proceso");
} else if (promedio >= 0) {
    console.log ("pesimo estudiante");
} else {
    console.log ("repite año escolar")
}






















